function withExpandedScripts(roles: Role[]): Role[] {
  return roles.map((role) => {
    const extra = SCRIPT_EXPANSIONS[role.name]
    const closing = SCRIPT_CLOSINGS[role.name]
    if (!extra && !closing) return role
    const expansion = `${extra ?? ''}${closing ? `\n${closing}` : ''}`
    const marker = /^其一、/m.exec(role.full_script)
    const fullScript = marker
      ? `${role.full_script.slice(0, marker.index)}${expansion}\n\n${role.full_script.slice(marker.index)}`
      : `${role.full_script}\n\n${expansion}`
    return { ...role, full_script: fullScript }
  })
}

