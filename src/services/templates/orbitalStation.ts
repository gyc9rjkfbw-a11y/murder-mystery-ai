function withExpandedScripts(roles: Role[]): Role[] {
  return roles.map((role) => {
    const body = SCRIPT_EXPANSIONS[role.name] ?? ''
    const recap = CLOCK_RECAPS[role.name] ?? ''
    if (!body && !recap) return role
    const marker = /^其[一二三四五六][、，,]/m.exec(role.full_script)
    // 钟点复盘并入「行为准则」段：这一段在 4/5/6 人局都不会被裁剪
    if (marker) {
      const head = role.full_script.slice(0, marker.index)
      const tail = role.full_script.slice(marker.index).replace(/^其一[、，,]/, `其一，${recap}`)
      return { ...role, full_script: `${head}${body ? `${body}\n\n` : ''}${tail}` }
    }
    const suffix = `${body ? `\n\n${body}` : ''}${recap ? `\n${recap}` : ''}`
    return { ...role, full_script: `${role.full_script}${suffix}` }
  })
}

